class Command(BaseCommand):
    help = 'تعبئة المهارات المعيارية الأساسية'

    def handle(self, *args, **options):
        created_count = 0
        updated_count = 0

        for track, code, name, desc, order in SKILLS_DATA:
            obj, created = SkillStandard.objects.update_or_create(
                code=code,
                defaults={
                    'track': track,
                    'name': name,
                    'description': desc,
                    'order': order,
                    'is_active': True,
                }
            )
            if created:
                created_count += 1
            else:
                updated_count += 1

        self.stdout.write(self.style.SUCCESS(
            f'✅ تم: {created_count} مهارة جديدة، {updated_count} مهارة محدّثة '
            f'(الإجمالي: {SkillStandard.objects.count()})'
        ))
